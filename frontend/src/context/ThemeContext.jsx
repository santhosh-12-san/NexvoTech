const THEMES_ARRAY = Object.values(THEMES);

const ThemeContext = createContext(null);

export const ThemeProvider = ({ children }) => {
  const [themeId, setThemeId] = useState(() => {
    return localStorage.getItem('nexvo_theme') || 'cyan';
  });

  const currentTheme = THEMES[themeId] || THEMES.cyan;
  const themeIndex = Math.max(0, THEMES_ARRAY.findIndex((t) => t.id === themeId));

  useEffect(() => {
    localStorage.setItem('nexvo_theme', themeId);
    const root = document.documentElement;

    root.style.setProperty('--nexvo-bg', currentTheme.bg);
    root.style.setProperty('--nexvo-surface', currentTheme.surface);
    root.style.setProperty('--nexvo-card', currentTheme.card);
    root.style.setProperty('--nexvo-card-hover', currentTheme.cardHover);
    root.style.setProperty('--nexvo-primary', currentTheme.primary);
    root.style.setProperty('--nexvo-secondary', currentTheme.secondary);
    root.style.setProperty('--nexvo-accent', currentTheme.accent);
    root.style.setProperty('--nexvo-glow', currentTheme.glowColor);
    root.style.setProperty('--nexvo-border-subtle', currentTheme.borderSubtle);
    root.style.setProperty('--nexvo-border-hover', currentTheme.borderHover);

    document.body.style.backgroundColor = currentTheme.bg;
  }, [themeId, currentTheme]);

  const selectTheme = (newId) => {
    if (THEMES[newId]) {
      setThemeId(newId);
    }
  };

  // Next theme in rotation sequence (loops 0 -> 23 -> 0)
  const nextTheme = () => {
    const nextIdx = (themeIndex + 1) % THEMES_ARRAY.length;
    const newTheme = THEMES_ARRAY[nextIdx];
    setThemeId(newTheme.id);
    return newTheme;
  };

  // Previous theme in rotation sequence
  const prevTheme = () => {
    const prevIdx = (themeIndex - 1 + THEMES_ARRAY.length) % THEMES_ARRAY.length;
    const newTheme = THEMES_ARRAY[prevIdx];
    setThemeId(newTheme.id);
    return newTheme;
  };

  const setThemeByIndex = (index) => {
    const normalized = (index % THEMES_ARRAY.length + THEMES_ARRAY.length) % THEMES_ARRAY.length;
    setThemeId(THEMES_ARRAY[normalized].id);
  };

  return (
    <ThemeContext.Provider
      value={{
        themeId,
        themeIndex,
        theme: currentTheme,
        themes: THEMES_ARRAY,
        setTheme: selectTheme,
        nextTheme,
        prevTheme,
        setThemeByIndex,
      }}
    >
      {children}
    </ThemeContext.Provider>
  );
};

export const useTheme = () => {
  const context = useContext(ThemeContext);
  if (!context) {
    throw new Error('useTheme must be used within a ThemeProvider');
  }
  return context;
};
